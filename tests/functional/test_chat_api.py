import base64
import pytest
import app
from tests.conftest import make_png_b64, make_pdf_bytes

pytestmark = pytest.mark.functional


def chat(client, tok, **body):
    body.setdefault("sid", "s1")
    return client.post(f"/api/chat?t={tok}", json=body)

def b64(b): return base64.b64encode(b).decode()


class TestTextChat:
    def test_happy_path(self, client, user, text_model):
        r = chat(client, user[1], message="What is entropy?")
        assert r.status_code == 200
        assert r.json() == {"reply": "Hello from the text model", "sid": "s1", "refresh_sidebar": True}

    def test_empty_message_rejected(self, client, user, text_model):
        assert chat(client, user[1], message="   ").json() == {"error": "empty"}
        assert text_model.calls == []

    def test_history_persisted_and_sent_back_to_model(self, client, user, text_model):
        chat(client, user[1], message="first")
        r = chat(client, user[1], message="second")
        assert r.json()["refresh_sidebar"] is False
        sent = text_model.calls[-1]["messages"]
        assert [m["content"] for m in sent if m["role"] != "system"] == ["first", "Hello from the text model", "second"]

    def test_system_prompt_always_first(self, client, user, text_model):
        chat(client, user[1], message="hi")
        assert text_model.calls[0]["messages"][0] == {"role": "system", "content": app.SYSTEM_PROMPT}

    def test_chat_title_is_first_message(self, client, user, text_model):
        chat(client, user[1], message="Explain photosynthesis please")
        chat(client, user[1], message="another")
        assert app.load_user("afrin")["chats"]["s1"]["title"] == "Explain photosynthesis please"

    def test_separate_sessions_do_not_mix(self, client, user, text_model):
        chat(client, user[1], sid="a", message="in A")
        chat(client, user[1], sid="b", message="in B")
        chats = app.load_user("afrin")["chats"]
        assert chats["a"]["history"][0]["content"] == "in A"
        assert chats["b"]["history"][0]["content"] == "in B"

    def test_missing_sid_autogenerated(self, client, user, text_model):
        r = client.post(f"/api/chat?t={user[1]}", json={"message": "hi"})
        assert r.json()["sid"]


class TestModelOutputSanitising:
    def test_think_block_never_reaches_user_or_disk(self, client, user, text_model):
        text_model.reply = "<think>secret plan</think>Final answer"
        r = chat(client, user[1], message="q")
        assert r.json()["reply"] == "Final answer"
        assert "secret plan" not in str(app.load_user("afrin"))

    def test_untagged_reasoning_is_stripped(self, client, user, text_model):
        text_model.reply = "Here's a thinking process:\n\n1. Analyze:\n- x\n\n2. Draft Response:\nReal answer"
        assert chat(client, user[1], message="q").json()["reply"] == "Real answer"


class TestTextModelFailures:
    def test_rate_limit_message(self, client, user, text_model):
        text_model.error = RuntimeError("429 Too Many Requests")
        assert "busy" in chat(client, user[1], message="q").json()["reply"]

    def test_generic_error_surfaced_not_500(self, client, user, text_model):
        text_model.error = RuntimeError("provider exploded")
        r = chat(client, user[1], message="q")
        assert r.status_code == 200 and "provider exploded" in r.json()["reply"]

    def test_error_reply_still_persisted(self, client, user, text_model):
        text_model.error = RuntimeError("boom")
        chat(client, user[1], message="q")
        assert len(app.load_user("afrin")["chats"]["s1"]["history"]) == 2


class TestPdfUpload:
    def test_pdf_text_reaches_model(self, client, user, text_model):
        pdf = make_pdf_bytes(["Second law of thermodynamics."])
        r = chat(client, user[1], message="summarise", file={"name": "notes.pdf", "mime": "application/pdf", "b64": b64(pdf)})
        assert r.status_code == 200
        prompt = text_model.calls[0]["messages"][-1]["content"]
        assert "notes.pdf" in prompt and "Second law of thermodynamics." in prompt

    def test_pdf_without_question_asks_for_summary(self, client, user, text_model):
        chat(client, user[1], message="", file={"name": "n.pdf", "mime": "application/pdf", "b64": b64(make_pdf_bytes())})
        assert "summarise" in text_model.calls[0]["messages"][-1]["content"].lower()

    def test_long_pdf_truncated_to_context_budget(self, client, user, text_model):
        pdf = make_pdf_bytes(["word " * 400] * 15)
        chat(client, user[1], message="q", file={"name": "big.pdf", "mime": "application/pdf", "b64": b64(pdf)})
        prompt = text_model.calls[0]["messages"][-1]["content"]
        assert "document truncated" in prompt

    def test_corrupt_pdf_handled_gracefully(self, client, user, text_model):
        r = chat(client, user[1], message="q", file={"name": "bad.pdf", "mime": "application/pdf", "b64": b64(b"junk")})
        assert r.status_code == 200
        assert "Could not read PDF" in text_model.calls[0]["messages"][-1]["content"]

    def test_history_label_for_file(self, client, user, text_model):
        chat(client, user[1], message="q", file={"name": "n.pdf", "mime": "application/pdf", "b64": b64(make_pdf_bytes())})
        assert app.load_user("afrin")["chats"]["s1"]["history"][0]["content"].startswith("📎 [File: n.pdf]")

    def test_plain_text_file(self, client, user, text_model):
        chat(client, user[1], message="q", file={"name": "a.txt", "mime": "text/plain", "b64": b64(b"hello notes")})
        assert "hello notes" in text_model.calls[0]["messages"][-1]["content"]


class TestImageUpload:
    def img(self, size=(40, 30)):
        return {"name": "shot.png", "mime": "image/png", "b64": make_png_b64(size)}

    def test_routes_to_vision_not_text(self, client, user, text_model, vision_model):
        r = chat(client, user[1], message="about this", file=self.img())
        assert r.json()["reply"] == "Hello from the vision model"
        assert text_model.calls == [] and len(vision_model.calls) == 1

    def test_requests_hidden_reasoning(self, client, user, vision_model):
        chat(client, user[1], message="x", file=self.img())
        assert vision_model.calls[0]["reasoning_format"] == "hidden"
        assert vision_model.calls[0]["model"] == app.VISION_MODEL

    def test_falls_back_when_reasoning_format_rejected(self, client, user, vision_model):
        vision_model.reject_reasoning_format = True
        r = chat(client, user[1], message="x", file=self.img())
        assert r.json()["reply"] == "Hello from the vision model"
        assert len(vision_model.calls) == 2 and "reasoning_format" not in vision_model.calls[1]

    def test_rate_limit_not_retried_and_friendly(self, client, user, vision_model):
        vision_model.error = RuntimeError("Error code: 429 rate limit")
        r = chat(client, user[1], message="x", file=self.img())
        assert "busy" in r.json()["reply"]

    def test_leaked_reasoning_stripped_from_vision_reply(self, client, user, vision_model):
        vision_model.reply = "Here's a thinking process:\n\n1. Analyze:\n- a\n\n5. Draft Response:\nClean answer"
        assert chat(client, user[1], message="x", file=self.img()).json()["reply"] == "Clean answer"

    def test_all_reasoning_no_answer_gives_friendly_fallback(self, client, user, vision_model):
        vision_model.reply = "<think>ran out of tokens thinking"
        assert "ran out of room" in chat(client, user[1], message="x", file=self.img()).json()["reply"]

    def test_large_image_resized_before_sending(self, client, user, vision_model):
        chat(client, user[1], message="x", file=self.img((4000, 3000)))
        url = vision_model.calls[0]["messages"][-1]["content"][-1]["image_url"]["url"]
        assert url.startswith("data:image/jpeg;base64,")

    def test_image_only_no_text(self, client, user, vision_model):
        assert chat(client, user[1], message="", file=self.img()).status_code == 200

    def test_history_label_for_image(self, client, user, vision_model):
        chat(client, user[1], message="what is this", file=self.img())
        assert app.load_user("afrin")["chats"]["s1"]["history"][0]["content"] == "📎 [Image: shot.png]\nwhat is this"
